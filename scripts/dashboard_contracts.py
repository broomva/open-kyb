"""Generate the browser's TypeScript contracts from the actual Pydantic API models."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from kyb.dashboard.contracts import (
    CaseMembership,
    ChatIntent,
    DashboardSnapshot,
    OpenSummary,
    RepairHandoff,
)

TARGET = Path(__file__).resolve().parents[1] / "src/kyb/dashboard/assets/contracts.d.ts"


def ts(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    if "anyOf" in schema:
        return "(" + " | ".join(ts(s) for s in schema["anyOf"]) + ")"
    kind = schema.get("type")
    if kind == "array":
        if "prefixItems" in schema:
            return "[" + ", ".join(ts(s) for s in schema["prefixItems"]) + "]"
        return f"Array<{ts(schema.get('items', {}))}>"
    if kind == "object":
        required = schema.get("required", [])
        fields = [
            f"{json.dumps(k)}{'' if k in required else '?'}: {ts(v)};"
            for k, v in schema.get("properties", {}).items()
        ]
        extra = schema.get("additionalProperties")
        if extra is not False:
            fields.append(f"[key: string]: {ts(extra) if isinstance(extra, dict) else 'unknown'};")
        return "{ " + " ".join(fields) + " }"
    return {
        "integer": "number",
        "number": "number",
        "string": "string",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def generate() -> str:
    definitions = {}
    for model in (DashboardSnapshot, OpenSummary, RepairHandoff, ChatIntent, CaseMembership):
        schema = model.model_json_schema()
        definitions.update(schema.pop("$defs", {}))
        definitions[model.__name__] = schema
    rows = ["// Generated by scripts/dashboard_contracts.py; edit the Python contracts instead."]
    rows += [f"export type {name} = {ts(schema)};" for name, schema in sorted(definitions.items())]
    rows.append("""
export type HostCapabilities = {
  serverTools?: object; message?: { text?: object }; openLinks?: object
};
declare global {
  interface Window {
    kybMaterials?: { refresh(): void; invalidate(): void };
    renderAt?: (time: number) => void;
  }
}
""")
    return "\n".join(rows)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rendered = generate()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != rendered:
            raise SystemExit(
                "Browser contracts are stale; run uv run python scripts/dashboard_contracts.py"
            )
    else:
        TARGET.write_text(rendered)
